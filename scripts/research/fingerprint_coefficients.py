#!/usr/bin/env python3
"""Regenerate the offline recognizer's verified mathematical tables (no DLL)."""
import argparse
from decimal import Decimal, localcontext
import gzip
from hashlib import sha256
import math
from pathlib import Path
import struct

ROOT = Path(__file__).resolve().parents[2]
SIGNAL = ROOT / "core/src/song_recognition/signal"
FIXTURES = ROOT / "core/tests/fixtures"
WINDOW_SIZE = 2048


def pack_f32(values):
    return b"".join(struct.pack("<f", value) for value in values)


def coefficient_tables():
    heads, tails, reciprocal = [], [], []
    with localcontext() as ctx:
        ctx.prec = 100
        for i in range(129):
            x = 1 + Decimal(i) / 128
            log = x.ln()
            nearest = struct.unpack("<I", struct.pack("<f", float(log)))[0]
            high = struct.unpack("<f", struct.pack("<I", nearest & ~4095))[0]
            residual = log - Decimal(high)
            low = struct.unpack("<I", struct.pack("<f", float(residual)))[0]
            if Decimal(struct.unpack("<f", struct.pack("<I", low))[0]) > residual:
                low -= 1
            heads.append(high)
            tails.append(struct.unpack("<f", struct.pack("<I", low))[0])
            reciprocal.append(float(2 / x))
    return tuple(map(pack_f32, (heads, tails, reciprocal)))


def write_or_check(path, data, write):
    if write:
        path.write_bytes(data)
    elif path.read_bytes() != data:
        raise SystemExit(f"generated bytes differ: {path.relative_to(ROOT)}")


def require_sha(data, expected):
    actual = sha256(data).hexdigest()
    if actual != expected:
        raise SystemExit(f"generated source differs from the verified SHA256: {actual}")
    return data


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true", help="replace committed coefficient files")
    args = parser.parse_args()

    window = require_sha(
        pack_f32(
            0.54 - 0.46 * math.cos(i * 2 * math.pi / (WINDOW_SIZE - 1))
            for i in range(WINDOW_SIZE)
        ),
        "45c215e0882e4f38e6430c779e331c251eafb396a9b1cd2e7cad3d6a4cd2d0bc",
    )
    twiddles = require_sha(
        pack_f32(
            func((-2 * math.pi * i) / WINDOW_SIZE)
            for i in range(WINDOW_SIZE)
            for func in (math.cos, math.sin)
        ),
        "37ea4f39cae858307222a5d42f50a92e7c74dd567e4185263e11fd26509df166",
    )
    logarithm = b"".join(
        require_sha(values, expected)
        for values, expected in zip(
            coefficient_tables(),
            (
                "4c76320e09085b9eb463c242e121da58e26a1f4fb30178d17ef20c9ce5441582",
                "f3749403d5d1f6f9c1aca320aef40a3eea25d128636a25fce91d330ff1b95211",
                "8c1e082036b2adc3a3bbec223fbeb32e62c311d5e5c2b935f9692b5640ad1794",
            ),
            strict=True,
        )
    )
    write_or_check(SIGNAL / "fft-coefficients.f32le", window + twiddles, args.write)
    write_or_check(SIGNAL / "log-coefficients.f32le", logarithm, args.write)

    # Only the transcendental synthetic fixture needs frozen PCM bytes.
    def sample(i):
        tone = 12000 * math.sin(2 * math.pi * (440 + (i // 1600 % 4) * 53) * i / 8000)
        backing = 4000 * math.sin(2 * math.pi * 841 * i / 8000)
        return round(tone + backing)

    pcm = require_sha(
        struct.pack("<24000h", *(sample(i) for i in range(24000))),
        "acfee201fea5ac1b004b21bd5bbc2ecc59f3be6586647f2c1fa7b8c63508337b",
    )
    fixture = FIXTURES / "song-recognition-two-tone.i16le.gz"
    if args.write:
        with fixture.open("wb") as raw, gzip.GzipFile(
            filename="", mode="wb", fileobj=raw, mtime=0
        ) as stream:
            stream.write(pcm)
    elif gzip.decompress(fixture.read_bytes()) != pcm:
        raise SystemExit("frozen two-tone fixture differs")


if __name__ == "__main__":
    main()
