//! Fixed native browser targets; no renderer-supplied URLs or credentials.
use cumulus_core::{Error, Result};
const CLOUD_CAPACITY_PAGE: &str = "https://music.163.com/#/vip";
pub async fn open_cloud_capacity() -> Result<()> {
    tauri::async_runtime::spawn_blocking(|| launch(CLOUD_CAPACITY_PAGE))
        .await
        .map_err(|_| Error::State("browser worker stopped"))?
}
#[cfg(target_os = "linux")]
fn launch(url: &str) -> Result<()> {
    launch_with(std::ffi::OsStr::new("xdg-open"), url)
}
#[cfg(target_os = "linux")]
fn launch_with(program: &std::ffi::OsStr, url: &str) -> Result<()> {
    use std::{process::Stdio, time::Duration};
    let mut child = std::process::Command::new(program)
        .arg(url)
        .stdin(Stdio::null())
        .stdout(Stdio::null())
        .stderr(Stdio::null())
        .spawn()?;
    for _ in 0..25 {
        if let Some(status) = child.try_wait()? {
            return if status.success() {
                Ok(())
            } else {
                Err(Error::State("browser failed to open"))
            };
        }
        std::thread::sleep(Duration::from_millis(20));
    }
    std::thread::Builder::new()
        .name("browser-reaper".into())
        .spawn(move || {
            let _ = child.wait();
        })?;
    Ok(())
}
#[cfg(windows)]
fn launch(url: &str) -> Result<()> {
    let target = std::ffi::OsString::from(url);
    std::thread::Builder::new()
        .name("browser-shell".into())
        .spawn(move || {
            crate::file_manager::windows_open_target(&target)
                .map_err(|_| Error::State("browser failed to open"))
        })?
        .join()
        .map_err(|_| Error::State("browser shell stopped"))?
}
#[cfg(not(any(target_os = "linux", windows)))]
fn launch(_: &str) -> Result<()> {
    Err(Error::State("browser opening unavailable"))
}
#[cfg(all(test, target_os = "linux"))]
mod tests {
    use super::*;
    use std::os::unix::fs::PermissionsExt;
    #[test]
    fn browser_launcher_reports_immediate_failure_and_passes_one_fixed_public_target() {
        let dir = tempfile::tempdir().unwrap();
        let script = dir.path().join("browser");
        // Test path is generated by tempfile and passed as a positional argument
        // through the executable's own directory; no user path interpolation.
        std::fs::write(
            &script,
            "#!/bin/sh\nprintf '%s\\n' \"$#\" \"$1\" > \"$0.receipt\"\n",
        )
        .unwrap();
        std::fs::set_permissions(&script, std::fs::Permissions::from_mode(0o700)).unwrap();
        launch_with(script.as_os_str(), CLOUD_CAPACITY_PAGE).unwrap();
        let receipt = dir.path().join("browser.receipt");
        assert_eq!(
            std::fs::read_to_string(receipt).unwrap(),
            format!("1\n{CLOUD_CAPACITY_PAGE}\n")
        );
        std::fs::write(&script, "#!/bin/sh\nexit 2\n").unwrap();
        assert!(launch_with(script.as_os_str(), CLOUD_CAPACITY_PAGE).is_err());
    }
}
